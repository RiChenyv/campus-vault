if (!existsSync(REAL)) {
  console.log(`  SKIP  这台机器上没有 ${REAL}`)
  console.log('  （这不是失败：上面的 fixture 就是照它造的。真文件在的话会额外核对一遍。）')
} else {
  const realBuf = readFileSync(REAL)
  const realSheet = readXlsx(realBuf)
  const real = parseGradesTable(realSheet.rows, { stringMode: realSheet.stringMode, sheetName: realSheet.name })

  eq('真实文件：29 条', real.grades.length, 29)
  eq('真实文件：忽略 8 列', real.ignoredColumns.length, 8)
  eq('真实文件：字符串模式 inline', real.stringMode, 'inline')
  eq('真实文件：表头 20 列', real.headers.length, 20)

  /* 关键：fixture 与真文件**逐字段一致** ——
     这一步同时验了"fixture 造得对不对"和"解析器稳不稳"。

     ⚠️ 比的时候**排除课程名**：公开仓库里的夹具把真实课程名换成了「通识示例课程四」
     这类通用名（个人信息不出仓库），而真文件里还是原名。
     课名只是个标签，夹具要证明的是**结构**（课程号、学期、分数、学分、绩点、
     类别、考核方式、考试日期…）与真文件一致 —— 那些字段一个都不能少。 */
  const stripName = (g) => ({ ...g, courseName: '' })
  check('★ fixture 与真实文件的解析结果**逐字段完全一致**（课名除外，见注释）',
    JSON.stringify(real.grades.map(stripName)) === JSON.stringify(p.grades.map(stripName)),
    (() => {
      for (let i = 0; i < Math.max(real.grades.length, p.grades.length); i++) {
        const a = JSON.stringify(stripName(real.grades[i] ?? {}))
        const b = JSON.stringify(stripName(p.grades[i] ?? {}))
        if (a !== b) return `第 ${i + 1} 条不同：真文件 ${a} / fixture ${b}`
      }
      return `条数不同：${real.grades.length} vs ${p.grades.length}`
    })())
  check('★ 真实文件的表头文字与 fixture 一致',
    real.headers.join('|') === p.headers.join('|'),
    `${real.headers.join('|')} vs ${p.headers.join('|')}`)
}


const colName = (i) => {
  let s = ''
  let n = i + 1
  while (n > 0) {
    const r = (n - 1) % 26
    s = String.fromCharCode(65 + r) + s
    n = Math.floor((n - 1) / 26)
  }
  return s
}

/**
 * 转义成"XML 里安全的文本"，但**不碰已有的实体引用**。
 *
 * ⚠️ 这里是最容易把 fixture 造漂的地方：H/D 里的文本本身就是
 * **XML 源码形态**（`&#23398;` 就是文件里那 8 个字符），不是"已解码的中文"。
 * 如果无脑 `&#` → `&amp;#`，文件里就变成了字面量 `&#23398;` 六个字符，
 * 解析器（正确地）只解一层 → 得到字面量而不是"学"，fixture 就和真实文件不是一回事了。
 * 所以只转义**真正的裸 &**（后面不是实体引用的那些）。
 */
const esc = (s) => String(s)
  .replace(/&(?!#\d+;|#x[0-9a-fA-F]+;|amp;|lt;|gt;|quot;|apos;)/g, '&amp;')
  .replace(/</g, '&lt;')
  .replace(/>/g, '&gt;')

/** 把二维数组写成 worksheet XML（内联字符串，与真实文件一致） */
function sheetXml(rows) {
  let out = '<?xml version="1.0" encoding="UTF-8"?>\n' +
    '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetData>\n'
  rows.forEach((cells, r) => {
    out += `<row r="${r + 1}">`
    cells.forEach((v, c) => {
      const ref = colName(c) + (r + 1)
      /* 空值写成自闭合的 `<c r=".."/>` —— 真实文件里"特殊原因"那一列就是这样 */
      out += v === '' || v === undefined || v === null
        ? `<c r="${ref}"/>`
        : `<c r="${ref}" t="inlineStr"><is><t>${esc(v)}</t></is></c>`
    })
    out += '</row>\n'
  })
  return out + '</sheetData></worksheet>'
}

/**
 * 把 sheetXml 里的内联字符串改写成**共享字符串**（用来测另一条分支）。
 *
 * `richAt` 指定的那条写成**两段式富文本**（`<r><t>…</t></r><r><t>…</t></r>`），
 * 用来验"按顺序拼接"而不是只取第一个 `<t>`（后者会丢后半截课程名）。
 */
function toSharedStrings(rows, richAt = -1) {
  const pool = []
  const index = new Map()
  for (const cells of rows) {
    for (const v of cells) {
      if (v === '' || v === undefined || v === null) continue
      if (!index.has(v)) { index.set(v, pool.length); pool.push(v) }
    }
  }
  let sheet = '<?xml version="1.0" encoding="UTF-8"?>\n' +
    '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetData>\n'
  rows.forEach((cells, r) => {
    sheet += `<row r="${r + 1}">`
    cells.forEach((v, c) => {
      const ref = colName(c) + (r + 1)
      if (v === '' || v === undefined || v === null) sheet += `<c r="${ref}"/>`
      else sheet += `<c r="${ref}" t="s"><v>${index.get(v)}</v></c>`
    })
    sheet += '</row>\n'
  })
  sheet += '</sheetData></worksheet>'

  const sst = '<?xml version="1.0" encoding="UTF-8"?>\n' +
    `<sst count="${pool.length}" uniqueCount="${pool.length}" xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">` +
    pool.map((s, i) => {
      const t = esc(s)
      if (i === richAt) {
        /* 从中间劈开 —— 只留住第一段的话长度会少一半，下面能断言出来 */
        const cut = Math.max(1, Math.floor(t.length / 2))
        return `<si><r><t>${t.slice(0, cut)}</t></r><r><t>${t.slice(cut)}</t></r></si>`
      }
      return `<si><t>${t}</t></si>`
    }).join('') +
    '</sst>'
  return { sheet, sst, pool, index }
}


section('⑫ 真读一遍用户那份 `全部成绩查询.xlsx`')

/* 真文件路径：默认当前用户的「下载」，可用 CV_GRADES_XLSX 覆盖 ——
   不写死某台机器的用户名（这个仓库要能给别人的机器跑） */

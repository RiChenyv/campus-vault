/**
 * 标准成绩表格。
 *
 * @param {{ dropColumns?: string[], headerOnly?: boolean }} opts
 *   `dropColumns` 按**解码后的列名**删列（用源码形态的实体编码当参数会一列都删不掉）
 *   `headerOnly` 只留表头（测"一条都没读到"）
 */
export function makeGradesXlsx(opts = {}) {
  let rows = [H, ...D]
  if (opts.headerOnly) rows = [H]
  if (opts.dropColumns?.length) {
    const drop = new Set(opts.dropColumns)
    /* 表头是实体编码的，得先解码才能按中文列名比对 —— 这里用一张小映射表，
       免得为了跑测试把解析器拖进来（fixture 生成器不该依赖被测代码）。 */
    const decoded = H.map(decodeForTest)
    const keep = decoded.map((h, i) => (drop.has(h) ? -1 : i)).filter((i) => i >= 0)
    rows = rows.map((r) => keep.map((i) => r[i]))
  }
  return makeZip([
    { name: '[Content_Types].xml', text: CONTENT_TYPES },
    { name: '_rels/.rels', text: '<?xml version="1.0"?><Relationships/>' },
    { name: 'docProps/app.xml', text: '<?xml version="1.0"?><Properties><Application>Apache POI</Application></Properties>' },
    { name: 'xl/workbook.xml', text: WORKBOOK },
    { name: 'xl/styles.xml', text: '<?xml version="1.0"?><styleSheet/>' },
    { name: 'xl/sharedStrings.xml', text: EMPTY_SST },
    { name: 'xl/worksheets/sheet1.xml', text: sheetXml(rows) },
  ])
}

/** 同一份数据，但用**共享字符串**写（真 Excel 的默认写法） */
export function makeGradesXlsxWithSharedStrings() {
  const rows = [H, ...D]
  const pool = []
  const index = new Map()
  for (const cells of rows) {
    for (const v of cells) {
      if (v === '' || v === undefined || v === null) continue
      if (!index.has(v)) { index.set(v, pool.length); pool.push(v) }
    }
  }
  let sheet = '<?xml version="1.0" encoding="UTF-8"?>\n' +
    '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetData>\n'
  rows.forEach((cells, r) => {
    sheet += `<row r="${r + 1}">`
    cells.forEach((v, c) => {
      const ref = colName(c) + (r + 1)
      sheet += v === '' || v === undefined || v === null
        ? `<c r="${ref}"/>`
        : `<c r="${ref}" t="s"><v>${index.get(v)}</v></c>`
    })
    sheet += '</row>\n'
  })
  sheet += '</sheetData></worksheet>'

  /* 第一条数据（课程名）写成两段式富文本：只取第一个 <t> 会丢后半截 */
  const richIdx = index.get(D[0][2])
  const sst = '<?xml version="1.0" encoding="UTF-8"?>\n' +
    `<sst count="${pool.length}" uniqueCount="${pool.length}" xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">` +
    pool.map((s, i) => {
      const t = esc(s)
      if (i === richIdx) {
        const cut = Math.max(1, Math.floor(t.length / 2))
        return `<si><r><t>${t.slice(0, cut)}</t></r><r><t>${t.slice(cut)}</t></r></si>`
      }
      return `<si><t>${t}</t></si>`
    }).join('') +
    '</sst>'

  return makeZip([
    { name: '[Content_Types].xml', text: CONTENT_TYPES },
    { name: 'xl/workbook.xml', text: WORKBOOK },
    { name: 'xl/sharedStrings.xml', text: sst },
    { name: 'xl/worksheets/sheet1.xml', text: sheet },
  ])
}

/** 只给 fixture 内部用：把实体编码的表头解成中文，便于按名字删列 */
function decodeForTest(s) {
  return String(s)
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(Number(d)))
    .replace(/&amp;/g, '&')
}


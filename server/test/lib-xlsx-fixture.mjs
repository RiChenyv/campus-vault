/**
 * 成绩表格（xlsx）测试用的 fixture 生成器。
 *
 * 两个测试共用它，避免 fixture 抄两份 —— 抄两份的话，
 * `grades-xlsx-api.mjs` 就会在**另一个**（可能已经漂了的）结构上做断言，
 * 而"接口能不能把真实文件吃下去"这件事就没人验了。
 *
 * 结构照抄教务系统真实导出的 `全部成绩查询.xlsx`（2026-10 实测）：
 *   · zip + deflate，条目名固定（[Content_Types].xml / xl/worksheets/sheet1.xml …）
 *   · 单元格是**内联字符串** `t="inlineStr"`，文本是 **HTML 实体编码**的
 *   · 表头 20 列，29 行数据
 *
 * ⚠️ 两条容易把 fixture 造漂的地方（都踩过）：
 *  1. `esc()` **不能**把已有的实体引用再转义一遍。这里存的文本本来就是
 *     **XML 源码形态**（`&#23398;` 就是文件里那 8 个字符），不是"已解码的中文"。
 *     无脑 `&` → `&amp;` 会让文件里出现字面量 `&#23398;`，解析器（正确地）
 *     只解一层，fixture 就和真实文件不是一回事了。
 *  2. 造**变体**（缺列等）时要拿**解析后的**表头，不能拿这里的源码形态常量。
 */

